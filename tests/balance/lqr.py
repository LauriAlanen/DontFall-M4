#!/usr/bin/env python3
"""LQR gains for the reaction wheel balancer (docs/balance-plan.md step 2).

Runs on the PC (needs numpy and scipy):

    tests/balance/lqr.py                          # print gains and poles
    tests/balance/lqr.py -o app/src/balance_gains.h
    tests/balance/lqr.py --plot                   # linear recovery from 5 deg

The model is the simulator's (tests/balance/src/plant.c), linearised about
upright, with state x = (theta, theta_dot, omega) and input the motor
torque. The controller is torque = -K x, K from a discrete LQR at the IMU
rate so the 1/850 s sample and hold is part of the design.

Weights by Bryson's rule: each state and the torque divided by the
largest value we accept for it, so the numbers below are the knobs.
"""

import argparse
import math

import numpy as np
from scipy.linalg import expm, solve_continuous_are, solve_discrete_are

# Same guesses as plant_guess in tests/balance/src/plant.c; keep in step.
M = 0.6                       # kg
L = 0.12                      # m
I_B = 0.6 * 0.2 ** 2 / 12     # kg m^2
I_W = 0.15 * 0.06 ** 2        # kg m^2
G = 9.80665                   # m/s^2
T_MAX = 0.2                   # N m, placeholder

DT = 1 / 850                  # s, measured IMU rate

# Largest acceptable values (Bryson). GUESSES like the parameters.
# Torque at a quarter of the limit keeps a 5 deg recovery under T_MAX;
# 2 deg and the full limit asked for 3x T_MAX (lqr.py --plot).
THETA_MAX = math.radians(5)   # rad, tilt while balancing
THETA_DOT_MAX = 2             # rad/s
OMEGA_MAX = 30                # rad/s, wheel; the gimbal motor is slow
TORQUE_MAX = T_MAX / 4


def model():
    j = I_B + M * L ** 2
    a = np.array([[0, 1, 0],
                  [M * G * L / j, 0, 0],
                  [-M * G * L / j, 0, 0]])
    b = np.array([[0], [-1 / j], [1 / j + 1 / I_W]])
    return a, b


def discretise(a, b, dt):
    """Zero-order hold: the torque is held for one sample."""
    n = a.shape[0]
    blk = np.zeros((n + 1, n + 1))
    blk[:n, :n] = a
    blk[:n, n:] = b
    e = expm(blk * dt)
    return e[:n, :n], e[:n, n:]


def weights():
    q = np.diag([1 / THETA_MAX ** 2, 1 / THETA_DOT_MAX ** 2, 1 / OMEGA_MAX ** 2])
    r = np.array([[1 / TORQUE_MAX ** 2]])
    return q, r


def gains():
    a, b = model()
    q, r = weights()
    ad, bd = discretise(a, b, DT)

    p = solve_discrete_are(ad, bd, q, r)
    k = np.linalg.solve(r + bd.T @ p @ bd, bd.T @ p @ ad)
    pc = solve_continuous_are(a, b, q, r)
    kc = np.linalg.solve(r, b.T @ pc)
    return (a, b, ad, bd), k.ravel(), kc.ravel()


def header(k, poles):
    deg = ", ".join(f"{z:.4f}" for z in poles)
    return f"""/*
 * Balance controller gains, torque = -(K_THETA theta + K_THETA_DOT
 * theta_dot + K_OMEGA omega), in N m per rad, per rad/s and per rad/s.
 *
 * GENERATED by tests/balance/lqr.py from the guessed parameters there;
 * change the script and rerun it, don't edit the numbers by hand.
 * Discrete LQR at {1 / DT:.0f} Hz, closed-loop poles |z| = {deg}.
 *
 * SPDX-License-Identifier: Apache-2.0
 */

#ifndef BALANCE_GAINS_H
#define BALANCE_GAINS_H

#define BALANCE_K_THETA     {k[0]:.6g}f
#define BALANCE_K_THETA_DOT {k[1]:.6g}f
#define BALANCE_K_OMEGA     {k[2]:.6g}f

#endif
"""


def recovery(ad, bd, k, start=math.radians(5), secs=2):
    """The linear closed loop from a tilt, no limits."""
    x = np.array([start, 0, 0])
    t, xs, us = [], [], []
    for n in range(int(secs / DT)):
        u = float(-k @ x)
        t.append(n * DT)
        xs.append(x)
        us.append(u)
        x = ad @ x + bd.ravel() * u
    return np.array(t), np.array(xs), np.array(us)


def plot(ad, bd, k):
    import matplotlib.pyplot as plt

    t, xs, us = recovery(ad, bd, k)

    fig, ax = plt.subplots(3, 1, sharex=True, figsize=(8, 7))
    ax[0].plot(t, np.degrees(xs[:, 0]))
    ax[0].set_ylabel("tilt θ (deg)")
    ax[1].plot(t, xs[:, 2])
    ax[1].axhline(OMEGA_MAX, ls=":", c="grey")
    ax[1].axhline(-OMEGA_MAX, ls=":", c="grey")
    ax[1].set_ylabel("wheel ω (rad/s)")
    ax[2].plot(t, us * 1000)
    ax[2].axhline(T_MAX * 1000, ls=":", c="grey")
    ax[2].axhline(-T_MAX * 1000, ls=":", c="grey")
    ax[2].set_ylabel("torque (mN m)")
    ax[2].set_xlabel("t (s)")
    for a in ax:
        a.grid(True)
    fig.suptitle("LQR, linear model, from 5° (dotted: limits, not enforced)")
    fig.tight_layout()
    return fig


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("-o", "--out", help="write the gains as a C header")
    ap.add_argument("--plot", nargs="?", const="", metavar="PNG",
                    help="plot a linear recovery from 5 deg (show, or save to PNG)")
    args = ap.parse_args()

    (a, b, ad, bd), k, kc = gains()
    ctrb = np.hstack([b, a @ b, a @ a @ b])
    open_poles = np.linalg.eigvals(a)
    poles = np.linalg.eigvals(ad - bd @ k[None, :])
    stable = np.all(np.abs(poles) < 1)

    print(f"controllable: {np.linalg.matrix_rank(ctrb) == 3}")
    print("open loop poles (1/s): " + ", ".join(f"{p.real:+.2f}" for p in open_poles))
    print(f"K discrete   : {k[0]:+.4f} {k[1]:+.5f} {k[2]:+.6f}")
    print(f"K continuous : {kc[0]:+.4f} {kc[1]:+.5f} {kc[2]:+.6f}")
    print("closed loop poles (1/s): "
          + ", ".join(f"{complex(np.log(z) / DT):.2f}" for z in poles))
    print(f"stable: {stable}")
    t, xs, us = recovery(ad, bd, k)
    settled = t[np.argmax(np.abs(xs[:, 0]) < math.radians(0.5))]
    print(f"from 5 deg: peak torque {np.max(np.abs(us)) * 1000:.0f} mN m "
          f"(limit {T_MAX * 1000:.0f}), peak wheel {np.max(np.abs(xs[:, 2])):.1f} rad/s, "
          f"under 0.5 deg after {settled:.2f} s")
    if not stable:
        raise SystemExit("closed loop not stable")

    if args.out:
        with open(args.out, "w") as f:
            f.write(header(k, np.abs(poles)))
        print(f"wrote {args.out}")
    if args.plot is not None:
        fig = plot(ad, bd, k)
        if args.plot:
            fig.savefig(args.plot, dpi=100)
        else:
            import matplotlib.pyplot as plt
            plt.show()


if __name__ == "__main__":
    main()
